CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    blocked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX idx_companies_name ON companies (name);

CREATE SEQUENCE vacancies_SEQ START WITH 1 INCREMENT BY 50;

CREATE TABLE vacancies (
    id BIGINT NOT NULL PRIMARY KEY,
    external_id VARCHAR(255) NOT NULL,
    source VARCHAR(255) NOT NULL,
    url TEXT NOT NULL,
    title VARCHAR(255) NOT NULL,
    company_id BIGINT NOT NULL,
    description TEXT NOT NULL,
    salary_fork VARCHAR(255) NOT NULL,
    match_score INTEGER NOT NULL,
    skills_breakdown JSONB,
    languages JSONB,
    applications_count INTEGER,
    status VARCHAR(32) NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_vacancies_company FOREIGN KEY (company_id) REFERENCES companies (id)
);

CREATE UNIQUE INDEX idx_vacancies_external_id ON vacancies (external_id);

CREATE INDEX idx_vacancies_status ON vacancies (status);

CREATE INDEX idx_vacancies_match_score ON vacancies (match_score);

CREATE INDEX idx_vacancies_matched_skills ON vacancies USING gin (
    (
        skills_breakdown -> 'matched_skills'
    )
);